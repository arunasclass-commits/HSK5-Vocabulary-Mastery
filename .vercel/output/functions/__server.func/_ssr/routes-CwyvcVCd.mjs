function bump(state, n, ok, kind) {
	const next = {
		...state,
		words: {
			...state.words,
			[n]: {
				...state.words[n],
				reasons: [...state.words[n]?.reasons ?? []]
			}
		},
		today: state.today.date === todayKey() ? { ...state.today } : freshToday(),
		sentences: state.sentences
	};
	const s = next.words[n];
	s.attempts += 1;
	s.last = Date.now();
	next.today.reviewed += 1;
	if (ok) {
		s.correct += 1;
		next.today.correct += 1;
		if (kind === "sentence") {
			s.sentence += 1;
			next.today.sentence += 1;
			s.level = s.level < 4 ? 4 : Math.min(6, s.level + 1);
		} else if (kind === "speak") {
			s.speaking += 1;
			next.today.speak += 1;
			s.level = s.level < 5 ? 5 : Math.min(7, s.level + 1);
		} else if (kind === "write") {
			s.writing += 1;
			next.today.write += 1;
			s.level = s.level < 4 ? 4 : Math.min(6, s.level + 1);
		} else if (s.level < 7) s.level += 1;
		const days = INTERVALS[Math.min(s.level, 7)];
		s.next = Date.now() + days * 864e5;
	} else {
		s.wrong += 1;
		s.level = Math.max(0, s.level - 1);
		s.next = Date.now();
		s.reasons = [...s.reasons, `${kind} miss ${todayKey()}`].slice(-4);
	}
	return next;
}
